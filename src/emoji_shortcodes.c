#define EMOJI_SC_COUNT ((int)(sizeof(g_emoji_sc) / sizeof(g_emoji_sc[0])))

static int sc_cmp(const char* a, int alen, const char* b) {
    for (int i = 0; i < alen; i++) {
        unsigned char ca = (unsigned char)a[i];
        unsigned char cb = (unsigned char)b[i];
        if (ca >= 'A' && ca <= 'Z') ca = (unsigned char)(ca - 'A' + 'a');
        if (!cb) return 1;
        if (ca != cb) return (int)ca - (int)cb;
    }
    return b[alen] ? -1 : 0;
}

static const EmojiSC* sc_lookup(const char* name, int name_len) {
    if (name_len <= 0 || name_len > 40) return NULL;
    int lo = 0, hi = EMOJI_SC_COUNT - 1;
    while (lo <= hi) {
        int mid = lo + ((hi - lo) >> 1);
        int c = sc_cmp(name, name_len, g_emoji_sc[mid].name);
        if (c == 0) return &g_emoji_sc[mid];
        if (c < 0) hi = mid - 1;
        else lo = mid + 1;
    }
    return NULL;
}

static int is_sc_char(unsigned char c) {
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
           (c >= '0' && c <= '9') || c == '_' || c == '+' || c == '-';
}

static int try_replace_at(char* buf, int* inout_len, int max_len,
                          int open_colon, int close_colon) {
    int name_start = open_colon + 1;
    int name_len = close_colon - name_start;
    if (name_len <= 0) return 0;
    for (int i = 0; i < name_len; i++) {
        if (!is_sc_char((unsigned char)buf[name_start + i])) return 0;
    }
    const EmojiSC* sc = sc_lookup(buf + name_start, name_len);
    if (!sc) return 0;
    int old_span = close_colon - open_colon + 1;
    int len = *inout_len;
    int delta = (int)sc->utf8_len - old_span;
    int new_len = len + delta;
    if (new_len < 0 || new_len >= max_len) return 0;

    int tail = len - (close_colon + 1);
    if (delta != 0 && tail > 0) {
        memmove(buf + open_colon + sc->utf8_len,
                buf + close_colon + 1,
                (size_t)tail);
    }
    memcpy(buf + open_colon, sc->utf8, sc->utf8_len);
    *inout_len = new_len;
    buf[new_len] = '\0';
    return 1;
}

bool emoji_expand_trailing(char* buf, int* inout_len, int max_len) {
    if (!buf || !inout_len || max_len < 4) return false;
    int len = *inout_len;
    if (len < 3 || buf[len - 1] != ':') return false;
    int close = len - 1;
    int open = -1;
    for (int i = close - 1; i >= 0; i--) {
        unsigned char c = (unsigned char)buf[i];
        if (c == ':') { open = i; break; }
        if (!is_sc_char(c)) return false;
    }
    if (open < 0) return false;
    if (close - open < 2) return false;
    return try_replace_at(buf, inout_len, max_len, open, close) != 0;
}

int emoji_expand_all(char* buf, int* inout_len, int max_len) {
    if (!buf || !inout_len || max_len < 4) return 0;
    int replaced = 0;
    int i = 0;
    while (i < *inout_len) {
        if (buf[i] != ':') { i++; continue; }
        int open = i;
        int j = open + 1;
        while (j < *inout_len && is_sc_char((unsigned char)buf[j])) j++;
        if (j < *inout_len && buf[j] == ':' && j > open + 1) {
            int name_len = j - (open + 1);
            const EmojiSC* sc = sc_lookup(buf + open + 1, name_len);
            if (sc && try_replace_at(buf, inout_len, max_len, open, j)) {
                replaced++;
                i = open + (int)sc->utf8_len;
                continue;
            }
        }
        i = open + 1;
    }
    return replaced;
}

bool emoji_active_prefix(const char* buf, int len, int* out_start, int* out_prefix_len) {
    if (!buf || len < 1) return false;
    int open = -1;
    for (int i = len - 1; i >= 0; i--) {
        unsigned char c = (unsigned char)buf[i];
        if (c == ':') { open = i; break; }
        if (!is_sc_char(c)) return false;
    }
    if (open < 0) return false;
    int plen = len - (open + 1);
    if (plen == 0 && open == len - 1) {
        if (out_start) *out_start = open;
        if (out_prefix_len) *out_prefix_len = 0;
        return true;
    }
    if (plen <= 0) return false;
    if (out_start) *out_start = open;
    if (out_prefix_len) *out_prefix_len = plen;
    return true;
}

static int prefix_match(const char* name, const char* prefix, int prefix_len) {
    for (int i = 0; i < prefix_len; i++) {
        unsigned char ca = (unsigned char)prefix[i];
        unsigned char cb = (unsigned char)name[i];
        if (ca >= 'A' && ca <= 'Z') ca = (unsigned char)(ca - 'A' + 'a');
        if (!cb || ca != cb) return 0;
    }
    return 1;
}

int emoji_suggest(const char* prefix, int prefix_len, EmojiSuggestion* out, int max_out) {
    if (!out || max_out <= 0) return 0;
    if (!prefix) prefix = "";
    if (prefix_len <= 0) return 0;
    int n = 0;
    for (int i = 0; i < EMOJI_SC_COUNT && n < max_out; i++) {
        if (!prefix_match(g_emoji_sc[i].name, prefix, prefix_len))
            continue;
        out[n].name = g_emoji_sc[i].name;
        out[n].utf8 = g_emoji_sc[i].utf8;
        n++;
    }
    return n;
}

bool emoji_apply_suggestion(char* buf, int* inout_len, int max_len, const char* selected_name) {
    if (!buf || !inout_len || !selected_name || !selected_name[0]) return false;
    int open = 0, plen = 0;
    if (!emoji_active_prefix(buf, *inout_len, &open, &plen)) return false;
    int name_len = (int)strlen(selected_name);
    const EmojiSC* sc = sc_lookup(selected_name, name_len);
    if (!sc) return false;
    int old_span = (*inout_len) - open;
    int new_len = open + (int)sc->utf8_len;
    if (new_len >= max_len) return false;
    memcpy(buf + open, sc->utf8, sc->utf8_len);
    *inout_len = new_len;
    buf[new_len] = '\0';
    (void)old_span;
    return true;
}
